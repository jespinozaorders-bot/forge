def ensure(c):
    """Insert any built-in exercise that is missing. Never touches user edits."""
    have = {r[0].lower() for r in c.execute("SELECT name FROM exercises")}
    new = [e for e in EXERCISES if e[0].lower() not in have]
    if new:
        c.executemany("INSERT INTO exercises(name,equipment,muscle,secondary,kind) VALUES(?,?,?,?,?)", new)
        c.commit()
    defaults = {"units": "lbs", "default_rest": "120", "max_hr": "", "birth_year": "",
                "rep_min": "8", "rep_max": "12"}
    for k, v in defaults.items():
        c.execute("INSERT OR IGNORE INTO settings(key,value) VALUES(?,?)", (k, v))
    c.commit()
